    // Non-owning resource-variable metadata. Images/fonts are pointers, while
    // sound slots remain int; never read sizeof(void*) from a four-byte sound.
    struct ResourceReference
    {
        enum class Kind { Image, Font, Sound };
        void* mAddress;
        Kind mKind;
        constexpr ResourceReference(Image** slot) : mAddress(slot), mKind(Kind::Image) {}
        constexpr ResourceReference(_Font** slot) : mAddress(slot), mKind(Kind::Font) {}
        constexpr ResourceReference(int* slot) : mAddress(slot), mKind(Kind::Sound) {}
        void* Value() const;
    };



    // The on-disk 1073 IDs interleave image, font and int32 sound slots.
    // Keep this independent of loaded resource objects for the converter.
    // Resources.cpp verifies every entry against its actual C++ slot type.
    constexpr bool IsImageResourceId(ResourceId id) noexcept
    {
        using enum ResourceId;
        return (id >= IMAGE_BLANK_ID && id <= IMAGE_REANIM_SODROLLCAP_ID) ||
            id == FONT_IMAGE_HOUSEOFTERROR28_ID || // Image* glyph atlas, not a _Font*.
            (id >= IMAGE_EDITBOX_ID && id <= IMAGE_REANIM_ZOMBIE_MUSTACHE3_ID) ||
            (id >= IMAGE_BACKGROUND1_ID && id <= IMAGE_ZOMBIE_NOTE_HELP_ID) ||
            (id >= IMAGE_REANIM_SUNFLOWER_HEAD_SING1_ID && id <= IMAGE_ZOMBATAR_VIEW_BUTTON_HIGHLIGHT_ID);
    }

