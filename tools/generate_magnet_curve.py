"""Generate the normalized, initially stationary inverse-square attraction curve."""
import argparse
import math
from pathlib import Path


def generate():
    count = 4096
    samples = []
    for i in range(count + 1):
        if i == 0:
            value = 1.0
        elif i == count:
            value = 0.0
        else:
            lo, hi = 0.0, math.pi / 2
            target = i / count * math.pi / 2
            for _ in range(60):
                theta = (lo + hi) / 2
                if theta + math.sin(theta) * math.cos(theta) < target:
                    lo = theta
                else:
                    hi = theta
            value = math.cos((lo + hi) / 2) ** 2
        samples.append(f"{value:.17g}" if value not in (0, 1) else f"{int(value)}.0")
    lines = ["// Generated by tools/generate_magnet_curve.py; r/r0 at uniform t/T0."]
    lines.extend("    " + ", ".join(samples[i:i + 8]) + "," for i in range(0, len(samples), 8))
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = Path(__file__).resolve().parents[1] / "pvzPerf/Lawn/MagnetMotionCurve.inc"
    text = generate()
    if args.check:
        if output.read_text(encoding="utf-8") != text:
            raise SystemExit("Magnet curve is stale; run tools/generate_magnet_curve.py")
    else:
        output.write_text(text, encoding="utf-8")
