#!/usr/bin/env python3
"""Bake numeric rich-text controls and substitution records into gStr values.

Textual control names exist only in this source compiler. --check compares all
source UI values, style transitions, and first-occurrence substitutions without
building or running the game. gStr field names/order stay unchanged.
"""
from __future__ import annotations

import argparse
import ast
from pathlib import Path
import re

FORMAT_NAMES = (
    "NORMAL", "FLAVOR", "KEYWORD", "NOCTURNAL", "AQUATIC", "STAT", "METAL",
    "KEYMETAL", "SHORTLINE", "EXTRASHORTLINE", "CREDITS1", "CREDITS2",
)
PLACEHOLDER_NAMES = (
    "PLAYER_NAME", "MONEY", "UPGRADE_COST", "COUNT", "FLAGS", "SCORE", "HEIGHT",
    "STREAK", "SEED", "PLAYER", "SLOTS", "SELL_PRICE", "PLANT_TYPE", "PAGE", "COST",
    "WAIT_TIME_LENGTH", "WAIT_TIME", "NUM_PAGES", "UPGRADE_TO", "UPGRADE_FROM",
)
FORMAT_MARKER, PLACEHOLDER_MARKER, NO_FORMAT = "\x1b", "\x1c", 0x7f
PLACEHOLDERS = {name: index for index, name in enumerate(PLACEHOLDER_NAMES, 1)}


def format_id(tag: str) -> int:
    # Original starts_with(name), in table order, deliberately accepts suffixes.
    return next((index for index, name in enumerate(FORMAT_NAMES, 1)
                 if tag.startswith(name)), NO_FORMAT)


def encode_ui_text(text: str) -> str:
    def record(match: re.Match) -> str:
        tag = match[1]
        if tag in PLACEHOLDERS:
            return PLACEHOLDER_MARKER + chr(PLACEHOLDERS[tag])
        return FORMAT_MARKER + chr(format_id(tag))
    return re.sub(r"\{([^}]*)\}", record, text)


def dave_bubble_text(text: str) -> str:
    # These two commands alone were replaced out of the old drawing copy.
    # All other hidden tags flushed a DrawString run and must keep a boundary.
    return text.replace("{SHAKE}", "", 1).replace("{NO_CLICK}", "", 1)


def bake_string_entries(strings: dict[str, str]) -> dict[str, str]:
    from gen_dave_dialogue_metadata import parse_dave_dialogue
    result = {}
    for key, value in strings.items():
        if re.fullmatch(r"CRAZY_DAVE_\d+", key):
            parse_dave_dialogue(value)  # Metadata compiler validates commands.
            value = dave_bubble_text(value)
        result[key] = encode_ui_text(value)
    return result


def decode_cpp_literal(expression: str) -> str:
    # Escaped bytes must round-trip as UTF-8, rather than Python's Latin-1 code
    # points. Adjacent C++ literal concatenation is handled by literal_eval.
    return ast.literal_eval(expression).encode("latin1").decode("utf-8")


def read_gstr(output: Path) -> tuple[list[str], list[str]]:
    fields = re.findall(r"std::string (\w+);", (output / "LawnStrings.h").read_text("utf-8"))
    values = []
    for line in (output / "LawnStrings.cpp").read_text("utf-8").splitlines():
        if "  // " in line and line.lstrip().startswith('"'):
            expression = line.split("  // ", 1)[0].strip().removesuffix(",")
            values.append(decode_cpp_literal(expression))
    return fields, values


def render_gstr(strings: dict[str, str]) -> str:
    from gen_entity_strings import ident, literal
    baked = bake_string_entries(strings)
    lines = ["//LawnStrings.cpp",
             "// Generated by reanimc bake-strings or tools/gen_numeric_text_controls.py. DO NOT EDIT.",
             "// UI text is unchanged; style/placeholder names and Dave commands are compiled offline.",
             "", '#include "LawnStrings.h"', "", "const LawnStrings gStr =", "{"]
    lines += ["\t" + literal(value) + ",  // " + key +
              (" (" + ident(key) + ")" if ident(key) != key else "")
              for key, value in baked.items()]
    return "\n".join(lines + ["};", ""])


def legacy_events(text: str) -> list[tuple[str, int | str]]:
    events = []
    offset = 0
    for match in re.finditer(r"\{([^}]*)\}", text):
        if match.start() > offset:
            events.append(("text", text[offset:match.start()]))
        events.append(("style", format_id(match[1])))
        offset = match.end()
    if offset < len(text):
        events.append(("text", text[offset:]))
    return events


def numeric_events(text: str) -> list[tuple[str, int | str]]:
    events = []
    offset = 0
    for match in re.finditer("[\x1b\x1c].", text, re.DOTALL):
        if match.start() > offset:
            events.append(("text", text[offset:match.start()]))
        events.append(("style", ord(match[0][1]) if match[0][0] == FORMAT_MARKER else NO_FORMAT))
        offset = match.end()
    if offset < len(text):
        events.append(("text", text[offset:]))
    return events


def draw_runs(events: list[tuple[str, int | str]], initial: int) -> list[tuple[int, str]]:
    # State transitions and run boundaries drive both glyph colors and wrapping.
    # Keep spaces/newlines exactly as the original Flavor flag does.
    style, previous_space = initial, False
    output = []
    for kind, value in events:
        if kind == "style":
            if value != NO_FORMAT:
                style = value
            continue
        text = ""
        for char in value:
            if style == 2:
                if char in " \n":
                    if not previous_space:
                        text += " "
                        previous_space = True
                    continue
                previous_space = False
            text += char
        output.append((style, text))
    return output


def visible_length(text: str, numeric: bool = False) -> int:
    data = text.encode("utf-8")
    length, offset, control = 0, 0, False
    while offset < len(data):
        byte = data[offset]
        if numeric and byte in (0x1b, 0x1c) and offset + 1 < len(data):
            offset += 2
            continue
        offset += 1
        if byte == ord("{"):
            control = True
        elif byte == ord("}"):
            control = False
        elif not control:
            length += 1
    return length


def verify_semantics(strings: dict[str, str]) -> tuple[int, int]:
    from gen_dave_dialogue_metadata import strip_dave_string_entries
    stripped = strip_dave_string_entries(strings)
    visible = {key: dave_bubble_text(value) if re.fullmatch(r"CRAZY_DAVE_\d+", key) else value
               for key, value in strings.items()}
    baked = bake_string_entries(strings)
    controls = replacements = 0
    for key, value in visible.items():
        encoded = baked[key]
        assert "\0" not in encoded, f"NUL in {key}"
        assert not re.search(r"\{[^}]*\}", encoded), f"Named control left in {key}"
        old_events, new_events = legacy_events(value), numeric_events(encoded)
        assert visible_length(strings[key]) == visible_length(encoded, True), f"Visible length drift in {key}"
        assert old_events == new_events, f"Text/style/run boundary drift in {key}"
        assert "".join(value for kind, value in new_events if kind == "text") == "".join(
            value for kind, value in legacy_events(stripped[key]) if kind == "text"), f"Dave visible text drift in {key}"
        for initial in range(1, 13):
            assert draw_runs(old_events, initial) == draw_runs(new_events, initial), key
        controls += sum(kind == "style" for kind, _ in old_events)
        for name, placeholder_id in PLACEHOLDERS.items():
            token = "{" + name + "}"
            record = PLACEHOLDER_MARKER + chr(placeholder_id)
            assert value.count(token) == encoded.count(record), (key, name)
            for substitute in ("", "Ada", "-2147483648", "2147483647", "42"):
                old = value.replace(token, substitute, 1)
                new = encoded.replace(record, substitute, 1)
                assert encode_ui_text(old) == new, (key, name, substitute)
            replacements += value.count(token)
    # All twelve styles, ordered-prefix matching, no-op tags, repeated first-only
    # replacement, literal UTF-8, and all twenty slots need coverage even when
    # a style/template is currently unused by the original corpus.
    for name in FORMAT_NAMES:
        for suffix in ("", "_SUFFIX"):
            fixture = "A{" + name + suffix + "}B"
            assert legacy_events(fixture) == numeric_events(encode_ui_text(fixture))
    for name, placeholder_id in PLACEHOLDERS.items():
        fixture = "{" + name + "}/{" + name + "}"
        encoded = encode_ui_text(fixture)
        assert encode_ui_text(fixture.replace("{" + name + "}", "7", 1)) == encoded.replace(
            PLACEHOLDER_MARKER + chr(placeholder_id), "7", 1)
    for fixture in ("A{}B", "{UNKNOWN}AB", "é{FLAVOR}  中\n 文", "{NORMAL_SUFFIX}text"):
        assert legacy_events(fixture) == numeric_events(encode_ui_text(fixture))
    for fixture in ("a{", "a}b", "a{{x}b", "{}", "a{bad", "a{tag}b", "{nested{tag}}b"):
        assert visible_length(fixture) == visible_length(encode_ui_text(fixture), True), fixture
    # Dave sound choice divides the visible byte count by three and compares
    # 23/52. Exercise all messages with the actual first-only substitutions and
    # player names containing malformed or nested user braces.
    for key, value in strings.items():
        if not re.fullmatch(r"CRAZY_DAVE_\d+", key):
            continue
        for player_name in ("Ada", "a{", "a}b", "a{{x}b", "é中"):
            old, new = value, baked[key]
            for name, substitute in (("PLAYER_NAME", player_name), ("MONEY", "$1,234"),
                                     ("UPGRADE_COST", "$500"), ("SELL_PRICE", "800"),
                                     ("PLANT_TYPE", "Wall-nut")):
                old = old.replace("{" + name + "}", substitute, 1)
                new = new.replace(PLACEHOLDER_MARKER + chr(PLACEHOLDERS[name]), substitute, 1)
            old_count, new_count = visible_length(old), visible_length(new, True)
            assert old_count == new_count, (key, player_name, old_count, new_count)
            assert (old_count // 3 < 23, old_count // 3 < 52) == (new_count // 3 < 23, new_count // 3 < 52)
    return controls, replacements


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path,
                        default=Path(__file__).resolve().parent.parent / "Sexy.TodLib/generated")
    parser.add_argument("--check", action="store_true")
    opts = parser.parse_args()
    from gen_entity_strings import ident, parse_strings
    strings = parse_strings(opts.input)
    assert len(strings) == 911, "Expected all 911 original1073 UI entries"
    controls, replacements = verify_semantics(strings)
    fields, values = read_gstr(opts.output_dir)
    assert fields == [ident(key) for key in strings], "gStr field ABI/order changed"
    expected = list(bake_string_entries(strings).values())
    if opts.check:
        assert values == expected, "gStr numeric UI values differ from the source compiler"
    else:
        # First migration proves the pre-existing UI values against original1073;
        # later reruns accept only the exact canonical already-baked values.
        assert values in (list(strings.values()), expected), "Existing gStr text differs from original1073"
        (opts.output_dir / "LawnStrings.cpp").write_text(render_gstr(strings), encoding="utf-8", newline="\n")
    print(f"Verified {len(strings)} UI values, {controls} style/placeholder records, {replacements} substitution occurrences, 12 styles and 20 slots; exact visible text and first-only substitutions preserved.")


if __name__ == "__main__":
    main()
