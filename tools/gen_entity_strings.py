#!/usr/bin/env python3
"""Bake runtime entity UI values without shipping localization key strings.

This is the source-only entry point for reanimc's entity table schema. Input is
an extracted original1073 properties/LawnStrings.txt; --check verifies the
checked-in outputs and the stable gStr fields without compiling the game.
"""
from __future__ import annotations

