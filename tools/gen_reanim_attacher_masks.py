# -*- coding: utf-8 -*-
"""reanim attacher 掩码编译期生成器（P4 后续，2026-10-02 用户指令）。

源：Sexy.TodLib/ReanimTrackMphfGlobal.h（reanimc compile-v2 签入产物）的
kSlots 槽表——全量 (type,id)→trackIndex 键，key=(uint64(type)<<32)|id；
与 Sexy.TodLib/ReanimTrackId.h 的 attacher__ 前缀区间（左闭右开）联查。

派生：
  kMaxReanimTracks        = 全类型轨道数 max（首见索引 max+1）
  kReanimAttacherMasks    = 每类型 attacher 轨道位掩码（id 落区间 → 其
                            轨道下标置位），uint64 字数组
输出：Sexy.TodLib/generated/ReanimAttacherMasks.h（仅 Reanimator.cpp 包含，
hpp/cpp 分离——改版重生成只重编一个 obj）。

改版流水线：reanimc 重跑 → ReanimTrackMphfGlobal.h 更新 → CMake 依赖触发
本脚本 → 新掩码/新长度自动生成。
"""
import io
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
MPHF = os.path.join(ROOT, 'pvzPerf', 'Sexy.TodLib', 'ReanimTrackMphfGlobal.h')
TRACKID = os.path.join(ROOT, 'pvzPerf', 'Sexy.TodLib', 'ReanimTrackId.h')
OUT = os.path.join(ROOT, 'pvzPerf', 'Sexy.TodLib', 'generated', 'ReanimAttacherMasks.h')


def parse_mphf_slots():
    """kSlots 槽表 → 实键 (type, id, index) 列表（key=0 为 padding）。"""
    text = io.open(MPHF, encoding='utf-8').read()
    m = re.search(r'kSlots\[kSlotCount\]\s*=\s*\{(.*?)\n    \};', text, re.S)
    if m is None:
        raise SystemExit('gen: kSlots table not found')
    slots = []
    for mm in re.finditer(r'\{0x([0-9a-fA-F]+)ull,\s*(\d+)\}', m.group(1)):
        key = int(mm.group(1), 16)
        index = int(mm.group(2))
        if key == 0:
            continue
        slots.append((key >> 32, key & 0xFFFFFFFF, index))
    return slots


def parse_attacher_mask_table():
    """编译器发射的 kAttacherMaskByType → (type_count, words, rows[])。

    掩码本体转写此表（原始轨道表计算，含同 id 重复轨道）；不再从 kSlots
    + attacher__ 区间自行推导（MPHF 首见折叠不含重复轨道）。
    """
    text = io.open(MPHF, encoding='utf-8').read()
    mc = re.search(r'kAttacherMaskTypeCount\s*=\s*(\d+)\s*;', text)
    mw = re.search(r'kAttacherMaskWords\s*=\s*(\d+)\s*;', text)
    mt = re.search(r'kAttacherMaskByType\[kAttacherMaskTypeCount\]\[kAttacherMaskWords\]\s*=\s*\{(.*?)\n\};', text, re.S)
    if mc is None or mw is None or mt is None:
        return None
    type_count, words = int(mc.group(1)), int(mw.group(1))
    rows = []
    for row in re.finditer(r'\{([^}]*)\}', mt.group(1)):
        words_list = [int(re.match(r'0x([0-9a-fA-F]+)ull', w.strip()).group(1), 16)
                      for w in row.group(1).split(',') if w.strip()]
        if len(words_list) != words:
            raise SystemExit('gen: mask row word count mismatch')
        rows.append(words_list)
    if len(rows) != type_count:
        raise SystemExit('gen: mask row count %d != type count %d' % (len(rows), type_count))
    return type_count, words, rows


def main():
    slots = parse_mphf_slots()
    if not slots:
        raise SystemExit('gen: kSlots has no real keys')
    masks_table = parse_attacher_mask_table()
    if not masks_table:
        raise SystemExit('gen: kAttacherMaskByType not found (rerun reanimc compile-v2 '
                         'with the mask-emitting Pak64.cpp)')

    # kMaxReanimTracks 仅作容量哨兵（static_assert <= 活动掩码容量），仍从
    # kSlots 首见索引推导；掩码本体转写编译器发射的 kAttacherMaskByType
    # （原始轨道表计算，含同 id 重复轨道——2026-10-06 credits 合影缺失案：
    # 此前从 kSlots 自行推导，MPHF 首见折叠丢了第二条 attacher__ZombieArmy2，
    # 该轨道运行时永不被驱动）。
    track_counts = {}
    for the_type, the_id, index in slots:
        if track_counts.get(the_type, -1) < index:
            track_counts[the_type] = index + 1

    type_count, words, mask_rows = masks_table
    max_tracks = max(track_counts.values())
    if words != (max_tracks + 63) // 64:
        raise SystemExit('gen: emitted mask words (%d) disagree with kSlots-derived '
                         'ceil(maxTracks/64) (%d)' % (words, (max_tracks + 63) // 64))

    lines = []
    lines.append('// Generated by tools/gen_reanim_attacher_masks.py from ReanimTrackMphfGlobal.h')
    lines.append('// (reanimc compile-v2 产物) -- DO NOT EDIT.')
    lines.append('// P4：每 reanim 类型的轨道数（MPHF 首见索引 max+1）与 attacher 轨道位掩码')
    lines.append('//（转写 kAttacherMaskByType：编译器按原始轨道表计算，含同 id 重复轨道），')
    lines.append('// 纯编译期常量，取代 ReanimatorLoadDefinitions 装载期建表。仅 Reanimator.cpp')
    lines.append('// 包含（hpp/cpp 分离：改版重生成只重编一个 obj；reanimc 重跑 → CMake 依赖联动）。')
    lines.append('#pragma once')
    lines.append('')
    lines.append('#include <cstdint>')
    lines.append('')
    lines.append('inline constexpr int kMaxReanimTracks = %d;  // 全类型最大轨道数（实测值随数据自动更新）' % max_tracks)
    lines.append('inline constexpr int kReanimAttacherTypeCount = %d;' % type_count)
    lines.append('inline constexpr int kReanimAttacherMaskWords = %d;  // = ceil(kMaxReanimTracks/64)' % words)
    lines.append('')
    lines.append('inline constexpr std::uint64_t kReanimAttacherMasks[kReanimAttacherTypeCount][kReanimAttacherMaskWords] = {')
    attacher_types = 0
    for t in range(type_count):
        word_arr = mask_rows[t] if t < len(mask_rows) else [0] * words
        if any(word_arr):
            attacher_types += 1
        rows = ', '.join('0x%016xull' % w for w in word_arr)
        lines.append('    {%s},  // type %d (%d tracks)'
                     % (rows, t, track_counts.get(t, 0)))
    lines.append('};')
    content = chr(10).join(lines) + chr(10)
    if not os.path.exists(OUT) or io.open(OUT, encoding='utf-8').read() != content:
        io.open(OUT, 'w', encoding='utf-8', newline=chr(10)).write(content)
        print('gen: wrote %s (changed)' % os.path.relpath(OUT, ROOT))
    print('gen: %d types, max %d tracks, %d words, %d attacher types -> %s'
          % (type_count, max_tracks, words, attacher_types, os.path.relpath(OUT, ROOT)))


if __name__ == '__main__':
    sys.exit(main())
